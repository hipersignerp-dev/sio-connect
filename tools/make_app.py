"""Packages the SIO scripts into the sio_connect Frappe app.

    python3 tools/make_app.py

Reads the same sources as server_scripts/build.py and writes:
  sio_connect/scripts/*.py      every script, exactly as the Server Script would hold it
  sio_connect/_registry.py      library script names -> files
  sio_connect/api/{auth,mobile,public}.py   whitelisted methods with the same paths the phone app calls
  sio_connect/events.py         document events, scheduled jobs, permission queries (see runtime.py)
  sio_connect/hooks_generated.py  doc_events / scheduler_events / permission_query_conditions for hooks.py
Run it (and commit the result) whenever server_scripts change.
"""

import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "server_scripts"))
import build  # noqa: E402

APP = os.path.join(ROOT, "sio_connect")
SCRIPTS = os.path.join(APP, "scripts")
HOOK = {"Before Insert": "before_insert", "After Insert": "after_insert", "Before Save": "validate",
        "After Save": "on_update", "After Delete": "after_delete", "Before Delete": "on_trash"}


def key_of(name):
    return re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")


def main():
    os.makedirs(SCRIPTS, exist_ok=True)
    for f in os.listdir(SCRIPTS):
        if f.endswith(".py"):
            os.remove(os.path.join(SCRIPTS, f))
    recs = build.records()
    libs = {}
    apis = {}  # module -> [(func, key, guest, ratelimit)]
    doc_events = {}
    events_py = ['"""Generated by tools/make_app.py: document events, scheduled jobs and permission queries."""',
                 "", "from sio_connect.runtime import doc_event, permission_query, scheduled", ""]
    for r in recs:
        key = key_of(r["name"])
        with open(os.path.join(SCRIPTS, key + ".py"), "w") as fh:
            fh.write(r["script"].rstrip("\n") + "\n")
        if r["script_type"] == "API" and r["api_method"].startswith("sio_connect.lib."):
            libs[r["name"]] = key
        elif r["script_type"] == "API":
            parts = r["api_method"].split(".")
            assert parts[0] == "sio_connect" and parts[1] == "api", r["api_method"]
            rl = (r.get("rate_limit_count"), r.get("rate_limit_seconds")) if r.get("enable_rate_limit") else None
            apis.setdefault(parts[2], []).append((parts[3], key, bool(r.get("allow_guest")), rl))
        elif r["script_type"] == "DocType Event":
            fn = "ev_" + key
            events_py += [f"def {fn}(doc, method=None):", f'\tdoc_event("{key}", doc)', "", ""]
            doc_events.setdefault(r["reference_doctype"], {}).setdefault(HOOK[r["doctype_event"]], []).append(
                "sio_connect.events." + fn)
    pqs = {}
    for f, (dt, label) in build.PQ.items():
        key = "pq_" + f
        with open(os.path.join(SCRIPTS, key + ".py"), "w") as fh:
            fh.write(build.read("permission", f + ".py").rstrip("\n") + "\n")
        events_py += [f"def {key}(user=None, **kwargs):", f'\treturn permission_query("{key}", user)', "", ""]
        pqs[dt] = "sio_connect.events." + key
    cron = {}
    for name, f, spec in [("task_reminders", "task_reminders", "0 8 * * *"),
                          ("streak_reminders", "streak_reminders", "30 19 * * *")]:
        key = "job_" + name
        with open(os.path.join(SCRIPTS, key + ".py"), "w") as fh:
            fh.write(build.read("events", f + ".py").rstrip("\n") + "\n")
        events_py += [f"def {key}():", f'\tscheduled("{key}")', "", ""]
        cron.setdefault(spec, []).append("sio_connect.events." + key)
    with open(os.path.join(APP, "events.py"), "w") as fh:
        fh.write("\n".join(events_py).rstrip("\n") + "\n")
    with open(os.path.join(APP, "_registry.py"), "w") as fh:
        fh.write('"""Generated by tools/make_app.py."""\n\nLIBS = ' + json.dumps(libs, indent=1) + "\n")
    for mod, fns in apis.items():
        out = [f'"""Generated by tools/make_app.py: the phone app\'s sio_connect.api.{mod}.* methods."""', "",
               "import frappe", "from frappe.rate_limiter import rate_limit", "", "from sio_connect.runtime import api",
               "", ""]
        for fn, key, guest, rl in sorted(fns):
            if guest:
                out.append("@frappe.whitelist(allow_guest=True)")
            else:
                out.append("@frappe.whitelist()")
            if rl:
                out.append(f"@rate_limit(limit={rl[0] or 5}, seconds={rl[1] or 86400})")
            out += [f"def {fn}(**kwargs):", f'\tapi("{key}", guest={guest})', "", ""]
        with open(os.path.join(APP, "api", mod + ".py"), "w") as fh:
            fh.write("\n".join(out).rstrip("\n") + "\n")
    gen = ['"""Generated by tools/make_app.py (imported by hooks.py)."""', "",
           "doc_events = " + json.dumps(doc_events, indent=1),
           "scheduler_events = " + json.dumps({"cron": cron}, indent=1),
           "permission_query_conditions = " + json.dumps(pqs, indent=1)]
    with open(os.path.join(APP, "hooks_generated.py"), "w") as fh:
        fh.write("\n".join(gen) + "\n")
    print(len(recs) + len(pqs) + len(cron), "scripts;", sum(len(v) for v in apis.values()), "API methods;",
          sum(len(x) for v in doc_events.values() for x in v.values()), "document events")


if __name__ == "__main__":
    main()
